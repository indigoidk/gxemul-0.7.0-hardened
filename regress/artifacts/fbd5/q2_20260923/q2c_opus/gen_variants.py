#!/usr/bin/env python3
"""Opus seat, #545 q2c: the variant list.

PART 1 -- the 434 variants of the earlier pass, regenerated by EXECUTING the earlier generator
(_scratchpad/fbd5/q2r/opus/driver.py, cut before its build loop, with the "dom" and "case" families
selected), so they are the same strings the main loop re-scored, not a transcription.

PART 2 -- NEW one-line shapes for step 3 (id prefix N).  Each carries a PREDICTION written before any
run: RED; EQ (green, equivalent); GREEN-DISC (green, a real change the contract's NOT COVERED list
names); GREEN-REAL (green, a real change NOT in that list -- a finding if measured so); GREEN-MACH
(green, equivalent only because no device in the tree drives the bit).
Each variant: dict(vid, family, arm, old, new, text, pred, note).  Every `old` must occur exactly once in
the frozen device (checked by check_anchors()).
"""
import io, os, sys

P = "/mnt/c/DocumentNoSnc/cc/GXEMUL"
FROZEN = P + "/_scratchpad/fbd5/q2c/frozen/dev_footbridge.c"
OLD_DRIVER = P + "/_scratchpad/fbd5/q2r/opus/driver.py"


def load434():
    src = io.open(OLD_DRIVER, encoding="utf-8").read()
    cut = src.index("assert len(set(v[0] for v in V)) == len(V)")
    src = src[:cut].replace('P + "/_scratchpad/fbd5/q2r/frozen/dev_footbridge.c"',
                            'P + "/_scratchpad/fbd5/q2c/frozen/dev_footbridge.c"')
    saved = sys.argv
    sys.argv = ["driver.py", "dom", "case"]
    ns = {"__name__": "gen434"}
    try:
        exec(compile(src, OLD_DRIVER, "exec"), ns)
    finally:
        sys.argv = saved
    out = []
    for vid, fam, arm, old, new, text in ns["V"]:
        out.append(dict(vid=vid, family=fam, arm=arm, old=old, new=new, text=text, pred="", note="q2r set"))
    return out, ns["ARMS"]


def new_shapes(ARMS):
    T = "\t"
    NL = "\n"
    V = []

    def add(vid, fam, arm, old, new, text, pred, note=""):
        V.append(dict(vid=vid, family=fam, arm=arm, old=old, new=new, text=text, pred=pred, note=note))

    def first_line(s):
        return s.split(NL)[0]

    def dir_(vid, arm, expr, pred, note=""):
        a = ARMS[arm]
        fl = first_line(a["dir_old"])
        tail = " {" if fl.endswith("{") else ""
        nl = T * 2 + "if (" + expr + ")" + tail
        add(vid, "N_dir", arm, a["dir_old"], a["dir_old"].replace(fl, nl, 1), "if (" + expr + ")" + tail, pred, note)

    def flag_(vid, arm, expr, pred, note=""):
        a = ARMS[arm]
        pre = T * 2 + ("} else if (" if arm == "A2" else "else if (")
        nl = pre + expr + ") {"
        add(vid, "N_flag", arm, a["flag_old"], nl, nl.strip(), pred, note)

    def body_(vid, arm, stmt, pred, note=""):
        a = ARMS[arm]
        add(vid, "N_body", arm, a["body_old"], T * 3 + stmt, stmt, pred, note)

    def read_(vid, arm, stmt, pred, note=""):
        a = ARMS[arm]
        old = a["read_old"]
        fl = first_line(old)
        add(vid, "N_read", arm, old, old.replace(fl, T * 3 + stmt, 1), stmt, pred, note)

    CLR = [T * 3 + "d->irq_enable &= ~idata;", T * 3 + "if (d->irq_status & d->irq_enable)",
           T * 4 + "INTERRUPT_ASSERT(d->irq);", T * 3 + "else", T * 4 + "INTERRUPT_DEASSERT(d->irq);"]
    CLR_OLD = NL.join(CLR) + NL + T * 2 + "} else if (!d->warned_irq_clear_r) {"

    def clr_(vid, fam, idx, line, pred, note=""):
        L = list(CLR)
        L[idx] = line
        add(vid, fam, "A2", CLR_OLD, NL.join(L) + NL + T * 2 + "} else if (!d->warned_irq_clear_r) {",
            line.strip(), pred, note)

    IDL = T + "if (writeflag == MEM_WRITE)" + NL + T * 2 + "idata = memory_readmax64(cpu, data, len);" + NL + NL \
        + T + "if (relative_addr >= TIMER_1_LOAD"

    def fetch_(vid, expr, pred, note=""):
        add(vid, "N_fetch", "head", IDL, IDL.replace(T + "if (writeflag == MEM_WRITE)", T + "if (" + expr + ")", 1),
            "if (" + expr + ") idata = memory_readmax64(...)", pred, note)

    FOLD = T + "if (relative_addr >= TIMER_1_LOAD && relative_addr <= TIMER_4_CLEAR) {"
    NR = T * 2 + "timer_nr = (relative_addr >> 5) & (N_FOOTBRIDGE_TIMERS - 1);"
    MASK = T * 2 + "relative_addr &= ~0x060;"

    # ---- L: width conditions on the latch test and the direction test (c_flag had `&& len == 4`,
    #         `&& len != 1`; c_dir had `&& len == 4 | != 1 | != 2`) -- width 8 is reachable (LDRD/STRD)
    flag_("N_L01", "A0", "!d->warned_irq_status_w || len == 1", "RED", "byte repeat re-announces")
    flag_("N_L02", "A1", "!d->warned_irq_raw_w && len != 2", "RED")
    flag_("N_L03", "A3", "!d->warned_fiq_status_w && len != 4", "RED")
    flag_("N_L04", "A4", "!d->warned_fiq_raw_w && len < 4", "RED")
    flag_("N_L05", "A2", "!d->warned_irq_clear_r && len <= 2", "RED")
    flag_("N_L06", "A0", "!d->warned_irq_status_w && len != 8", "GREEN-REAL", "8-byte STRD declined write not announced")
    dir_("N_L07", "A0", "writeflag == MEM_READ && len != 8", "GREEN-REAL", "8-byte LDRD read of IRQ_STATUS declined, reads 0")
    dir_("N_L08", "A2", "writeflag == MEM_WRITE && len <= 4", "GREEN-REAL", "8-byte STRD Clear write declined")
    dir_("N_L09", "A1", "writeflag == MEM_READ || len == 1", "RED")
    flag_("N_L10", "A3", "!d->warned_fiq_status_w || len == 8", "GREEN-REAL", "host: re-announce on every 8-byte write")
    dir_("N_L11", "A4", "writeflag == MEM_READ && len < 8", "GREEN-REAL", "host: 8-byte FIQ_RAW_STATUS read declined")
    # ---- D: idata inside the status arms
    flag_("N_D01", "A0", "!d->warned_irq_status_w && idata != 0x70", "RED")
    flag_("N_D02", "A1", "!d->warned_irq_raw_w && idata < 0x100", "GREEN-DISC", "wide data on a declined write")
    flag_("N_D03", "A3", "!d->warned_fiq_status_w && idata != 0x55", "GREEN-DISC", "narrow data not in {0,0x70}")
    dir_("N_D04", "A0", "writeflag == MEM_READ && !idata", "EQ", "idata is 0 on every read")
    dir_("N_D05", "A4", "writeflag == MEM_READ || !idata", "RED")
    dir_("N_D06", "A1", "writeflag == MEM_READ || idata > 0xff", "GREEN-DISC", "wide data")
    read_("N_D07", "A0", "odata = d->irq_status & d->irq_enable & ~idata;", "EQ")
    read_("N_D08", "A1", "odata = d->irq_status | idata;", "EQ")
    flag_("N_D09", "A2", "!d->warned_irq_clear_r && !idata", "EQ", "idata is 0 on the declined read")
    dir_("N_D10", "A3", "writeflag == MEM_READ || idata == 0x70", "RED")
    flag_("N_D11", "A4", "!d->warned_fiq_raw_w && (idata & 1) == 0", "GREEN-DISC", "odd declined data")
    # ---- S: operator swaps -- the Clear arm's drive test and the guards
    clr_("N_S01", "N_drive", 1, T * 3 + "if (d->irq_status && d->irq_enable)", "GREEN-REAL")
    clr_("N_S02", "N_drive", 1, T * 3 + "if (d->irq_enable)", "GREEN-REAL")
    clr_("N_S03", "N_drive", 1, T * 3 + "if (d->irq_status | d->irq_enable)", "RED")
    clr_("N_S04", "N_drive", 1, T * 3 + "if (d->irq_status & d->irq_enable & ~idata)", "EQ", "ne already excludes idata")
    clr_("N_S05", "N_drive", 1, T * 3 + "if (d->irq_status & ~d->irq_enable)", "RED")
    clr_("N_S06", "N_drive", 1, T * 3 + "if (d->irq_status & d->irq_enable & ~0x400u)", "GREEN-REAL", "bit 10, cats ISA")
    clr_("N_S07", "N_drive", 1, T * 3 + "if (d->irq_status & d->irq_enable & 0xffff00ffu)", "GREEN-REAL", "byte 1")
    clr_("N_S08", "N_drive", 1, T * 3 + "if (d->irq_status & d->irq_enable & 0x7fffffffu)", "GREEN-MACH", "bit 31")
    clr_("N_S09", "N_drive", 1, T * 3 + "if (d->irq_status & d->irq_enable & 0xffffu)", "RED")
    dir_("N_S10", "A0", "writeflag <= MEM_READ", "EQ")
    dir_("N_S11", "A1", "!writeflag", "EQ")
    dir_("N_S12", "A3", "writeflag == MEM_READ || writeflag == MEM_WRITE", "RED")
    flag_("N_S13", "A1", "d->warned_irq_raw_w == 0", "EQ")
    flag_("N_S14", "A4", "d->warned_fiq_raw_w < 1", "EQ")
    flag_("N_S15", "A0", "!d->warned_irq_status_w || !d->warned_irq_raw_w", "RED")
    dir_("N_S16", "A2", "writeflag & MEM_WRITE", "EQ")
    clr_("N_S17", "N_drive", 1, T * 3 + "if (d->irq_status & (d->irq_enable | idata))", "RED")
    clr_("N_S18", "N_drive", 1, T * 3 + "if (d->irq_status & d->irq_enable & ~d->fiq_enable)", "RED", "ones")
    # ---- B: the latch-set line / the decline body
    body_("N_B01", "A0", "d->warned_irq_status_w = len;", "EQ")
    body_("N_B02", "A2", "d->warned_irq_clear_r = writeflag;", "RED")
    body_("N_B03", "A3", "d->warned_fiq_status_w = !d->warned_fiq_status_w;", "EQ")
    body_("N_B04", "A4", "d->warned_fiq_raw_w++;", "EQ")
    body_("N_B05", "A1", "d->warned_irq_raw_w = d->irq_enable;", "RED")
    body_("N_B06", "A0", "d->warned_irq_status_w = 1 + d->irq_status;", "RED", "ones only: 1 + 0xffffffff == 0")
    body_("N_B07", "A2", "d->warned_irq_clear_r = 1; odata = d->irq_enable;", "RED")
    body_("N_B08", "A0", "d->warned_irq_status_w = 1; odata = 0;", "EQ")
    body_("N_B09", "A1", "d->warned_irq_raw_w = 1; d->irq_status &= ~idata;", "RED")
    body_("N_B10", "A0", "d->warned_irq_status_w = (idata != 0x55);", "GREEN-DISC", "data 0x55 leaves the latch clear")
    # ---- T: timer_nr, the timer arrays, and irq_asserted -- fields NEITHER branch reads
    dir_("N_T01", "A0", "writeflag == MEM_READ && !timer_nr", "EQ", "timer_nr is 0 at all five")
    dir_("N_T02", "A2", "writeflag == MEM_WRITE && timer_nr == 0", "EQ")
    flag_("N_T03", "A1", "!d->warned_irq_raw_w || timer_nr", "EQ")
    dir_("N_T04", "A0", "writeflag == MEM_READ && !d->timer_control[0]", "GREEN-REAL", "DEVINIT sets PERIODIC")
    dir_("N_T05", "A1", "writeflag == MEM_READ && !d->timer_load[0]", "GREEN-REAL", "DEVINIT sets TIMER_MAX_VAL")
    dir_("N_T06", "A2", "writeflag == MEM_WRITE && !d->pending_timer_interrupts[0]", "GREEN-REAL")
    flag_("N_T07", "A3", "!d->warned_fiq_status_w && !d->timer_value[0]", "GREEN-DISC", "latch guard, neither-branch field")
    flag_("N_T08", "A1", "!d->warned_irq_raw_w && d->pending_bound[0] <= 1", "GREEN-DISC", "latch guard")
    dir_("N_T09", "A4", "writeflag == MEM_READ || d->timer_control[3]", "GREEN-REAL", "host: declines silent from reset")
    flag_("N_T10", "A2", "!d->warned_irq_clear_r && !d->irq_asserted", "GREEN-DISC", "latch guard")
    dir_("N_T11", "A0", "writeflag == MEM_READ && !d->irq_asserted", "GREEN-REAL", "the ISR's status read returns 0")
    dir_("N_T12", "A2", "writeflag == MEM_WRITE && !d->irq_asserted", "GREEN-REAL", "a Clear write in the ISR is declined")
    # ---- F: the write-data fetch narrowed by a field / an address
    fetch_("N_F01", "writeflag == MEM_WRITE && !d->irq_asserted", "GREEN-REAL")
    fetch_("N_F02", "writeflag == MEM_WRITE && d->irq_enable", "RED")
    fetch_("N_F03", "writeflag == MEM_WRITE && !d->irq_enable", "RED")
    fetch_("N_F04", "writeflag == MEM_WRITE && !d->fiq_status", "RED")
    fetch_("N_F05", "writeflag == MEM_WRITE && d->fiq_enable", "RED")
    fetch_("N_F06", "writeflag == MEM_WRITE && !d->warned_irq_clear_r", "RED")
    fetch_("N_F07", "writeflag == MEM_WRITE && d->warned_irq_status_w == 0", "RED")
    fetch_("N_F08", "writeflag == MEM_WRITE && len != 2", "RED")
    fetch_("N_F09", "writeflag == MEM_WRITE && !d->timer_control[0]", "GREEN-REAL", "every write fetches 0 from reset")
    fetch_("N_F10", "writeflag == MEM_WRITE && relative_addr != IRQ_STATUS", "EQ", "Q1(c): no decline reads idata")
    fetch_("N_F11", "writeflag == MEM_WRITE && relative_addr != IRQ_RAW_STATUS && relative_addr != FIQ_STATUS"
           " && relative_addr != FIQ_RAW_STATUS", "EQ", "Q1(c)")
    fetch_("N_F12", "writeflag == MEM_WRITE || relative_addr == IRQ_ENABLE_CLEAR", "EQ",
           "Q1(c): the +0x18c declined read sees buffer bytes in idata")
    fetch_("N_F13", "writeflag == MEM_WRITE && relative_addr != IRQ_ENABLE_CLEAR", "RED", "control: the legal Clear reads idata")
    fetch_("N_F14", "writeflag == MEM_WRITE && !timer_nr", "EQ", "the fetch precedes the fold")
    fetch_("N_F15", "writeflag == MEM_WRITE && !d->pending_timer_interrupts[0]", "GREEN-REAL")
    # ---- I: the interrupt-output helpers in the Clear arm
    clr_("N_I01", "N_irq", 1, T * 3 + "if ((d->irq_status & d->irq_enable) && !d->irq_asserted)", "GREEN-REAL",
         "the NetBSD `&& !d->irq_asserted` form, in the Clear arm")
    clr_("N_I02", "N_irq", 4, T * 4 + "if (!d->irq_asserted) INTERRUPT_DEASSERT(d->irq);", "GREEN-REAL")
    clr_("N_I03", "N_irq", 4, T * 4 + "if (d->irq_asserted) INTERRUPT_DEASSERT(d->irq);", "RED")
    clr_("N_I04", "N_irq", 1, T * 3 + "if (d->irq_status & d->irq_enable || d->irq_asserted)", "GREEN-REAL")
    clr_("N_I05", "N_irq", 2, T * 4 + "INTERRUPT_ASSERT(d->timer_irq[0]);", "GREEN-REAL", "wrong target, same counter")
    clr_("N_I06", "N_irq", 4, T * 4 + "INTERRUPT_DEASSERT(d->timer_irq[3]);", "GREEN-REAL", "wrong target, same counter")
    clr_("N_I07", "N_irq", 2, T * 4 + "INTERRUPT_DEASSERT(d->irq);", "RED")
    clr_("N_I08", "N_irq", 4, T * 4 + "INTERRUPT_ASSERT(d->irq);", "RED")
    clr_("N_I09", "N_irq", 1, T * 3 + "if (d->irq_status & d->irq_enable & ~d->fiq_status)", "RED", "ones")
    # ---- R: a legal branch that re-arms (clears) a latch -- X7's class
    read_("N_R01", "A0", "odata = d->irq_status & d->irq_enable, d->warned_irq_status_w = 0;", "RED")
    read_("N_R02", "A1", "odata = d->irq_status, d->warned_irq_raw_w = 0;", "RED")
    clr_("N_R03", "N_rearm", 0, T * 3 + "d->irq_enable &= ~idata, d->warned_irq_clear_r = 0;", "RED")
    read_("N_R04", "A3", "odata = d->fiq_status & d->fiq_enable, d->warned_fiq_status_w &= !(d->fiq_enable >> 24);",
          "RED", "ones only, and only X7 re-declines after a legal read")
    read_("N_R05", "A0", "odata = d->irq_status & d->irq_enable, d->warned_irq_raw_w &= !d->irq_asserted;",
          "GREEN-REAL", "host: a latch CLEARER keyed on a neither-branch field")
    read_("N_R06", "A4", "odata = d->fiq_status, d->warned_irq_status_w = d->warned_irq_status_w && len != 2;", "RED")
    clr_("N_R07", "N_rearm", 0, T * 3 + "d->irq_enable &= ~idata, d->warned_irq_status_w &= (idata != 0);", "RED")
    # ---- H: the timer fold
    add("N_H01", "N_fold", "head", FOLD, T + "if (relative_addr <= TIMER_4_CLEAR) {", "if (relative_addr <= TIMER_4_CLEAR) {",
        "GREEN-DISC", "address axis; the five are unchanged by the fold")
    add("N_H02", "N_fold", "head", MASK, T * 2 + "relative_addr &= ~0x0e0;", "relative_addr &= ~0x0e0;", "EQ",
        "bit 7 is clear in every folded address")
    add("N_H03", "N_fold", "head", MASK, T * 2 + "relative_addr &= ~0x160;", "relative_addr &= ~0x160;", "RED")
    add("N_H04", "N_fold", "head", NR, T * 2 + "timer_nr = (relative_addr >> 5) & 7;", "timer_nr = (relative_addr >> 5) & 7;",
        "EQ", "(0x300..0x36c) >> 5 is 24..27")
    add("N_H05", "N_fold", "head", FOLD,
        T + "if (relative_addr >= TIMER_1_LOAD && relative_addr <= TIMER_4_CLEAR + 0x10) {",
        "if (relative_addr >= TIMER_1_LOAD && relative_addr <= TIMER_4_CLEAR + 0x10) {", "GREEN-DISC", "other registers")
    # ---- C: a dropped break (one line)
    add("N_C01", "N_break", "A0", T * 2 + "}" + NL + T * 2 + "break;" + NL + NL + T + "case IRQ_RAW_STATUS:",
        T * 2 + "}" + NL + NL + T + "case IRQ_RAW_STATUS:", "IRQ_STATUS arm: break removed", "RED")
    add("N_C02", "N_break", "A4", T * 2 + "}" + NL + T * 2 + "break;" + NL + NL + T + "case FIQ_ENABLE_SET:",
        T * 2 + "}" + NL + NL + T + "case FIQ_ENABLE_SET:", "FIQ_RAW_STATUS arm: break removed", "RED")
    add("N_C03", "N_break", "A2", T * 2 + "}" + NL + T * 2 + "break;" + NL + NL + T + "case FIQ_STATUS:",
        T * 2 + "}" + NL + NL + T + "case FIQ_STATUS:", "IRQ_ENABLE_CLEAR arm: break removed", "RED")
    # ---- SB (second table, added after the first table measured N_S06/N_S07 green): ONE BIT removed from the
    #      Clear arm's drive test, for every bit.  The rowed Clear cells leave (irq_status & new enable) equal to a
    #      single bit only at bit 4 (seeded, Clear 0) and bit 16 (wide, Clear 0x70 / all-ones len 1, 2); everywhere
    #      else it is 0 or many bits.  Prediction: RED for bits 4 and 16 only.
    for b in range(32):
        clr_("N_SB%02d" % b, "N_drivebit", 1, T * 3 + "if (d->irq_status & d->irq_enable & ~(1u << %d))" % b,
             "RED" if b in (4, 16) else "GREEN-REAL" if b in (5, 6, 7, 10, 11, 18) else "GREEN-MACH",
             "lines 4-7, 10, 11, 18 are driven on cats/netwinder")
    # ---- X (second table): probes for the families that held NOTHING alone in the first table -- one shape each that
    #      only that family should catch, to tell "redundant" from "vacuous".
    clr_("N_X1", "N_probe", 1, T * 3 + "if ((d->irq_status & d->irq_enable) && !d->warned_irq_raw_w)", "RED",
         "X10W only: the Clear write drives nothing while +0x184's latch is set")
    body_("N_X2", "A0", "d->warned_irq_status_w = 1; d->irq_status &= (len == 2 && (d->irq_enable >> 31)) ? 0u : ~0u;",
          "RED", "X6W only: a len-2 decline store keyed on enable bit 31 (ones state); X10's declines are len 4")
    clr_("N_X3", "N_probe", 0, T * 3 + "d->irq_enable &= ~idata, d->warned_irq_raw_w &= (d->irq_enable >> 24) != 0xff;",
         "RED", "X7W only: a legal Clear write that re-arms +0x184's latch when enable byte 3 stays 0xff (ones)")
    return V


def variants():
    v434, ARMS = load434()
    vn = new_shapes(ARMS)
    allv = v434 + vn
    ids = [v["vid"] for v in allv]
    assert len(ids) == len(set(ids)), "duplicate variant ids"
    assert len(v434) == 434, len(v434)
    return allv


def check_anchors(allv):
    fz = io.open(FROZEN, encoding="utf-8", newline="").read()
    bad = []
    for v in allv:
        n = fz.count(v["old"])
        if n != 1 or v["old"] == v["new"]:
            bad.append((v["vid"], n))
    return bad


if __name__ == "__main__":
    allv = variants()
    bad = check_anchors(allv)
    print("variants:", len(allv), " q2r:", sum(1 for v in allv if not v["vid"].startswith("N_")),
          " new:", sum(1 for v in allv if v["vid"].startswith("N_")), " anchor errors:", bad)
    if len(sys.argv) > 1 and sys.argv[1] == "pred":
        for v in allv:
            if v["vid"].startswith("N_"):
                print("%-7s %-8s %-5s %-11s %s   [%s]" % (v["vid"], v["family"], v["arm"], v["pred"], v["text"], v["note"]))
