#!/usr/bin/env python3
"""Generate TABLE.out for repair_20260909 by READING the logs.

Every number in the output is extracted from a log file on disk -- the 16-row column from
repair_20260909/logs/, the 14-row column from killtable2_20260907/.  Nothing is transcribed,
so the frozen-number class cannot reach this file.  Each log is verified by its COMPLETION
SENTINEL before its score is read; a log without one is reported as such and its score is
NOT used.

usage: mk_table.py <artifacts-dir> <out-file>
"""
import os, re, sys

ART = sys.argv[1]                       # .../artifacts/sgimtedepth4dead
OUT = sys.argv[2]
NEW = os.path.join(ART, "repair_20260909", "logs")
#  The 14-row column comes from TWO earlier dirs and it matters which: the nine ordinary
#  mutants were measured in killtable2_20260907, and the two LABEL mutants only existed later,
#  in killtable3_20260909, which is where their 14/14 total escapes were measured.  Looking in
#  one dir only silently prints "n/a" for exactly the two rows the repair is about.
OLDDIRS = [os.path.join(ART, "killtable2_20260907"),
           os.path.join(ART, "killtable3_20260909")]

SENTINEL = "MTEFILL_DONE"

# The pre-registered predictions, transcribed from PRETABLE.out (written before the table
# ran).  They are here ONLY so the generator can flag a deviation; the MEASURED column never
# comes from this dict.
PREDICT = {
    "BASE": "16/16 (measured before the table -- not a prediction)",
    "M_tlbA": "14/16", "M_tlbAB": "15/16", "M1_reinstate": "10/16", "M2_nodst": "9/16",
    "M3_nosrc": "13/16", "M4_copyonly": "10/16", "M5_dstrgb": "14/16", "M6_ge16": "14/16",
    "M7_ne8": "14/16", "M8_srcrgb": "15/16", "M9_ge32": "15/16", "NULL_dead": "0/16",
}
EDIT = {
    "BASE":         "none -- the shipped #509 fix",
    "M_tlbA":       "if (depth == 32 && dst_tlb == MTE_TLB_A) {",
    "M_tlbAB":      "if (depth == 32 && dst_tlb != MTE_TLB_C) {",
    "M1_reinstate": "if (depth == 4) {                     [clause (b), verbatim]",
    "M2_nodst":     "delete  dst_mode |= DE_MODE_TYPE_RGBA;",
    "M3_nosrc":     "delete  src_mode |= DE_MODE_TYPE_RGBA;",
    "M4_copyonly":  "if (depth == 32 && (mode & MTE_MODE_COPY)) {",
    "M5_dstrgb":    "dst_mode |= DE_MODE_TYPE_RGB;",
    "M6_ge16":      "if (depth >= 16) {",
    "M7_ne8":       "if (depth != 8) {",
    "M8_srcrgb":    "src_mode |= DE_MODE_TYPE_RGB;",
    "M9_ge32":      "if (depth >= 32) {",
    "NULL_dead":    "no build -- the frozen probe pointed at /bin/true",
}
ORDER = ["BASE", "M_tlbA", "M_tlbAB", "M1_reinstate", "M2_nodst", "M3_nosrc", "M4_copyonly",
         "M5_dstrgb", "M6_ge16", "M7_ne8", "M8_srcrgb", "M9_ge32", "NULL_dead"]


def readlog(p):
    """-> (score, sentinel_ok, [red row names], nrows)"""
    if not os.path.exists(p):
        return (None, False, None, None)
    t = open(p, encoding="latin-1").read()
    lines = [l for l in t.split("\n")]
    tail = [l for l in lines if l.strip()][-1] if any(l.strip() for l in lines) else ""
    ok = tail.strip() == SENTINEL
    m = re.search(r"^MTEFILL_RESULT=(\d+)/(\d+)$", t, re.M)
    score = "%s/%s" % (m.group(1), m.group(2)) if m else None
    n = int(m.group(2)) if m else None
    reds = []
    for l in lines:
        if l.endswith("FAIL") and not l.startswith("MTEFILL"):
            reds.append(l[:12].strip())
    return (score, ok, reds, n)


def readold(name):
    for d in OLDDIRS:
        p = os.path.join(d, name + ".raw")
        if os.path.exists(p):
            s, ok, r, n = readlog(p)
            return s, ok, r, os.path.basename(d)
    return None, False, None, None


rows = []
for name in ORDER:
    s16, ok16, r16, n16 = readlog(os.path.join(NEW, name + ".raw"))
    s14, ok14, r14, src14 = readold(name)
    rows.append((name, s16, ok16, r16, s14, src14, r14))

L = []
w = L.append
w("=" * 90)
w("KILL TABLE -- sgimtelabelcells, the L2 repair of #509's detector")
w("Generated by mk_table.py, which READS every log; no score in this file is transcribed.")
w("Instrument: sgi_mte_fill_probe.REPAIRED.py (16 rows), frozen for the whole table.")
w("Baseline:   GXEMUL-SEC/src/devices/dev_sgi_re.c at HEAD e73623a, md5 8479c1ea...")
w("Clone:      /tmp/gxopus7g1b (cp -a of build/), sentinel-disciplined, restored from SEC.")
w("=" * 90)
w("")
w("Each 16-row score below was read from repair_20260909/logs/<name>.raw after that log's")
w("MTEFILL_DONE sentinel was checked.  Each 14-row score was read the same way from the dir")
w("named in its own column -- the shipped detector's own measured numbers, not figures copied")
w("out of a round block.  THE COLUMN IS THERE BECAUSE THE 14-ROW SCORES LIVE IN TWO DIRS: the")
w("nine ordinary mutants in killtable2_20260907, and the two LABEL mutants in")
w("killtable3_20260909, which is where their 14/14 total escapes were measured.  A generator")
w("reading one dir prints 'n/a' for exactly the two rows this repair is about.")
w("")
w("%-14s %-9s %-9s %-9s %-22s %s" % ("mutant", "14-row", "16-row", "predict", "14-row measured in", "sentinel / note"))
w("-" * 108)
for name, s16, ok16, r16, s14, src14, r14 in rows:
    note = []
    if s16 is None:
        note.append("*** NO 16-ROW LOG ***")
    elif not ok16:
        note.append("*** SENTINEL MISSING -- score NOT trusted ***")
    else:
        note.append("MTEFILL_DONE")
    pred = PREDICT.get(name, "?")
    if s16 and pred and pred.split()[0] != s16 and name != "BASE":
        note.append("*** DEVIATES FROM PREDICTION ***")
    w("%-14s %-9s %-9s %-9s %-22s %s" % (name, s14 or "n/a", s16 or "MISSING", pred.split()[0], src14 or "-", "  ".join(note)))
w("-" * 108)
w("")
w("THE EDITS, so the table is re-runnable without reading the drivers:")
for name in ORDER:
    w("  %-14s %s" % (name, EDIT[name]))
w("")
w("=" * 90)
w("RED ROWS PER MUTANT -- 16-row run vs the 14-row run, so a LOST KILL would show as a row")
w("that reddened at 14 and is green at 16.  That is the check the repair owes the nine")
w("preserved mutants: adding rows must not take a kill away.")
w("=" * 90)
lost_any = False
for name, s16, ok16, r16, s14, src14, r14 in rows:
    if s16 is None:
        continue
    w("")
    w("%s   14-row %s -> 16-row %s" % (name, s14 or "n/a", s16))
    if r14 is not None:
        w("    reds at 14: %s" % (", ".join(r14) if r14 else "(none)"))
    w("    reds at 16: %s" % (", ".join(r16) if r16 else "(none)"))
    if r14 is not None:
        lost = [x for x in r14 if x not in r16]
        gained = [x for x in r16 if x not in r14]
        if lost:
            lost_any = True
            w("    *** LOST KILL(S): %s ***" % ", ".join(lost))
        else:
            w("    LOST KILLS: none")
        if gained:
            w("    GAINED: %s" % ", ".join(gained))
w("")
w("=" * 90)
w("VERDICT")
w("=" * 90)
base = dict((r[0], r[1]) for r in rows)
reds16 = dict((r[0], r[3]) for r in rows)


def frac(s):
    """'14/16' -> (14, 16); None on anything unparseable, so a missing log cannot read as a pass."""
    if not s:
        return None
    m = re.match(r"^(\d+)/(\d+)$", s)
    return (int(m.group(1)), int(m.group(2))) if m else None


def below_base(name):
    """Did this mutant score STRICTLY below the base, and is the base a clean sweep?
    Computed from the parsed logs -- an unparseable or missing score answers NO, never YES."""
    b, m = frac(base.get("BASE")), frac(base.get(name))
    if not b or not m:
        return "NO -- score missing or unparseable (%s vs base %s)" % (base.get(name), base.get("BASE"))
    if b[0] != b[1]:
        return "INDETERMINATE -- the base is not a clean sweep (%s)" % base.get("BASE")
    if m[1] != b[1]:
        return "INDETERMINATE -- different denominators (%s vs %s)" % (base.get(name), base.get("BASE"))
    return ("YES  (%s vs base %s; killed by: %s)" % (base.get(name), base.get("BASE"),
            ", ".join(reds16.get(name) or []) or "(none)")) if m[0] < b[0] else \
           ("*** NO -- STILL A TOTAL ESCAPE (%s vs base %s) ***" % (base.get(name), base.get("BASE")))


w("  every existing kill preserved across all nine: %s" % ("*** NO -- see LOST KILL above ***" if lost_any else "YES"))
w("  M_tlbA  scores below base: %s" % below_base("M_tlbA"))
w("  M_tlbAB scores below base: %s" % below_base("M_tlbAB"))
w("  NULL_dead reds every row:  %s" % ("YES  (%s)" % base.get("NULL_dead")
                                       if frac(base.get("NULL_dead")) and frac(base.get("NULL_dead"))[0] == 0
                                       else "*** NO (%s) ***" % base.get("NULL_dead")))
w("")
w("  Each line above is computed from the parsed logs.  An earlier draft of this generator")
w("  printed \"YES\" for the two M_tlb rows unconditionally -- a check that cannot fail, which")
w("  is worse than no check because it reassures.  It now answers NO on a missing score, a")
w("  mismatched denominator, or a mutant that did not actually drop below the base.")
open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
print("\n".join(L))
