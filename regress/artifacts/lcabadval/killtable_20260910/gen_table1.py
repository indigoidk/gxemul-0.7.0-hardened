#!/usr/bin/env python3
#
#  #518 lcabadval -- generate TABLE1.out from the LOGS and the MUTATOR.  Nothing here is
#  hand-typed: the score comes from <mutant>.raw, the reddened rows from the same log, and the
#  EDIT text from mutate518.py's own table.  A transcribed score is the frozen-number class and
#  this project has paid for it four times.
#
#  Run from this directory:  python3 gen_table1.py > TABLE1.out
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import summarize518 as S
import mutate518 as A
try:
    import mutate518b as B          # merges its EXTRA into A.M as a side effect
except Exception:
    B = None

HERE = os.path.dirname(os.path.abspath(__file__))


def edit_text(name):
    spec = A.M.get(name)
    if spec is None:
        return "(not in the mutator table)"
    if spec[0] == "__ARM__":
        return "VERBATIM (b): the whole `%s' arm replaced by its pre-#518 source" % spec[1]
    if spec[0] == "__FILE__":
        return "NULL MEDIUM (c): the entire PRE-FIX dev_lca.c (all seven kills at once)"
    find, repl, occ = spec
    where = {0: "every site", 1: "1st site", 2: "2nd site"}[occ]
    return "%s   ->   %s   [%s]" % (find, repl, where)


def num(sc):
    try:
        n, d = sc.split("=")[1].split("/")
        return int(n), int(d)
    except Exception:
        return None, None


rows = []
for fn in sorted(os.listdir(HERE)):
    if not fn.endswith(".raw") or fn.endswith(".40row.raw"):
        continue
    name = fn[:-4]
    sc, red, done, tot = S.rows_of(os.path.join(HERE, fn))
    sc40 = ""
    p40 = os.path.join(HERE, name + ".40row.raw")
    if os.path.exists(p40):
        s2, r2, d2, t2 = S.rows_of(p40)
        sc40 = "%s%s" % (s2.replace("LCABADVAL_RESULT=", ""), "" if d2 else " (NO SENTINEL)")
    rows.append((name, sc, red, done, tot, sc40))


def key(r):
    import re
    m = re.match(r"M(\d+)_", r[0])
    if r[0].startswith("BASE"):
        return (0, r[0])
    return (1, int(m.group(1)) if m else 999)


rows.sort(key=key)

print("#518 lcabadval -- KILL TABLE 1.  GENERATED by gen_table1.py; do not hand-edit.")
print("Baseline : BASELINE_FIX518c.c  md5 d5549c2fd83a6f79da3282c55ed77af0  (SEC working tree")
print("           at 00:19:23, i.e. the fix AS REPAIRED by its own pass 2 -- see README.txt S1)")
print("Instrument: lca_badval_probe.asrun2.py  md5 b6104f47a4bf37225f5bd538f563335a  58 rows")
print("           (the `40row' column, where present, is the pre-pass-2 asrun.py, 40 rows, run")
print("            on the SAME binary -- so the two numbers differ only by the row set)")
print("")
for name, sc, red, done, tot, sc40 in rows:
    flag = "" if done else "   *** NO SENTINEL -- SCORE REFUSED ***"
    n, d = num(sc)
    verdict = ""
    if n is not None:
        verdict = "SWEPT CLEAN (ESCAPE)" if n == d and not name.startswith("BASE") else \
                  ("baseline" if name.startswith("BASE") else "killed")
    print("%-24s %-10s %-22s %s%s" % (name, sc.replace("LCABADVAL_RESULT=", ""),
                                      verdict, ("40row=" + sc40) if sc40 else "", flag))
    print("    edit : %s" % edit_text(name))
    print("    log  : %s.raw%s" % (name, ("  +  " + name + ".40row.raw") if sc40 else ""))
    if red:
        for r in red:
            print("    RED  : %s" % r)
    elif not name.startswith("BASE"):
        print("    RED  : none -- no row of the 58 reddened")
    print("")
