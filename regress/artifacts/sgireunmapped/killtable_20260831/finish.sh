#!/bin/bash
set -u
H=/mnt/c/Users/User00/AppData/Local/Temp/claude/C--DocumentNoSnc-cc-GXEMUL/8e474f41-4d47-4c99-bf11-3406a84c4fcd/scratchpad/o499
SEC=/mnt/c/DocumentNoSnc/cc/GXEMUL/GXEMUL-SEC
PRISTINE=$SEC/src/devices/dev_sgi_re.c
CLONE=/tmp/gx499
cd $H

# ---- 1. the base (test-first) control, captured to a FILE this time -------
echo "BASE CONTROL -- the unmodified HEAD build.  Test-first: this MUST be red." > $H/base_detector.out
echo "binary $CLONE/gxemul.base  md5 $(md5sum $CLONE/gxemul.base | cut -d' ' -f1)" >> $H/base_detector.out
python3 -u $H/detector.run.py $CLONE/gxemul.base base >> $H/base_detector.out 2>&1
tail -2 $H/base_detector.out

# ---- 2. the four extra rows ----------------------------------------------
bash $H/extra.sh > $H/extra_rows.out 2>&1
tail -3 $H/extra_rows.out

# ---- 3. the baseline-identity record -------------------------------------
{
echo "BASELINE IDENTITY -- round #499 kill table, opus5 measuring seat"
echo "written $(date '+%Y-%m-%d %H:%M:%S')"
echo
echo "HEAD                 : $(cd $SEC && git rev-parse HEAD)"
echo "HEAD short           : $(cd $SEC && git rev-parse --short HEAD)"
echo "file under test      : src/devices/dev_sgi_re.c"
echo "md5 (SEC HEAD)       : $(md5sum $PRISTINE | cut -d' ' -f1)"
echo "md5 (clone, restored): $(md5sum $CLONE/src/devices/dev_sgi_re.c | cut -d' ' -f1)"
echo
echo "SCRATCH CLONE        : $CLONE   (cp -a of /tmp/gxopus_sgire, itself a cp -a of build/)"
echo "  clone src/ vs SEC src/, excluding *.o and crash dumps:"
diff -rq --exclude='*.o' --exclude='grep.exe.stackdump' $CLONE/src $SEC/src 2>&1 | sed 's/^/    /'
echo "  ^ the SEC-only ARC/Jazz enablement layer declared in tools/est_divergence.txt"
echo "    plus the two generated .index files that follow from it.  NONE of these is"
echo "    reachable from -E sgi -e ip32, which is the only machine this table boots."
echo
echo "RESTORE STATE"
cmp -s $CLONE/src/devices/dev_sgi_re.c $PRISTINE && echo "  part1 source cmp vs SEC : CLEAN" || echo "  part1 : DIFFERS"
if [ $CLONE/gxemul -nt $CLONE/src/devices/dev_sgi_re.c ]; then echo "  part2 [ binary -nt source ] : YES"; else echo "  part2 : NO"; fi
[ -f $CLONE/.MUTANT ] && echo "  SENTINEL PRESENT: $(cat $CLONE/.MUTANT)" || echo "  sentinel: absent (cleared after a verified restore)"
echo
echo "VARIANT BINARIES (any two identical md5s would mean a mis-build)"
md5sum $CLONE/gxemul.* | sort | sed 's/^/  /'
echo "  restored clone binary /tmp/gx499/gxemul:"
md5sum $CLONE/gxemul | sed "s/^/  /"
echo "  ^ must equal gxemul.base above: the restore rebuild reproduces the baseline binary"
echo
echo "BUILD FRESHNESS -- every variant checked [ binary -nt source ] inside the loop;"
echo "the checks are in table499.out beside each variant."
echo "BASELINE_DONE"
} > $H/BASELINE.out 2>&1
tail -2 $H/BASELINE.out

# ---- 4. the exact variant diffs ------------------------------------------
{
echo "VARIANT DIFFS -- generated by mkvariant499.py from HEAD's dev_sgi_re.c."
echo "Each is shown against the FIX, except `fix` itself which is shown against HEAD."
D=/tmp/gx499dry
for V in fix fix6 m1_tlba m2_tlbb m3_tlbc m4_bitcollide; do
  python3 $H/mkvariant499.run.py $V $PRISTINE $D/$V.c 2>/dev/null
done
echo
echo "########## HEAD -> fix ##########"
diff -u $D/../gx499dry/fix.c $D/fix.c >/dev/null 2>&1
diff -u $PRISTINE $D/fix.c
for V in fix6 m1_tlba m2_tlbb m3_tlbc m4_bitcollide; do
  echo
  echo "########## fix -> $V ##########"
  diff -u $D/fix.c $D/$V.c
done
echo "VARIANT_DIFFS_DONE"
} > $H/VARIANT_DIFFS.out 2>&1
tail -1 $H/VARIANT_DIFFS.out
echo "FINISH_DONE"
